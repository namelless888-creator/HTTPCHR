export const PRODUCTS: Product[] = CATALOG.map((item, index) => ({
  ...item,
  n: index + 1,
  id: String(index + 1).padStart(2, '0'),
  category: productCategory(index + 1),
  taste: details[index][0],
  description: details[index][1],
  brand: item.name.startsWith('MARZO') ? 'MARZO' : item.name.includes('Бурёнка') ? 'Бурёнка' : item.name.includes('My Love') ? 'My Love' : 'RAMCAD',
  ...(index === 1 ? { weight: '100 г' } : {}),
}));

export const productHref = (product: Pick<Product, 'id'>) => `/product/${product.id}`;
export const getProduct = (id: string) => PRODUCTS.find(product => product.id === id);
